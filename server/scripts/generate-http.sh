#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/../.."
mode="${1:-write}"
if [[ "$mode" != write && "$mode" != --check ]]; then
    echo "Usage: bash server/scripts/generate-http.sh [--check]" >&2
    exit 1
fi

version=1.1.0
tool_root="${WIEN_HTTPGENERATOR_ROOT:-target/tools}/httpgenerator-$version"
generator="$tool_root/bin/httpgenerator"
if [[ ! -x "$generator" ]]; then
    cargo install httpgenerator --version "=$version" --locked --root "$tool_root"
fi

mkdir -p target
staging=$(mktemp -d target/http-generate.XXXXXX)
trap 'rm -rf "$staging"' EXIT

cargo run --quiet -p wien-server --locked \
    --example export-openapi > "$staging/openapi.json"
# 1.1.0 renders OpenAPI 3.1 but its CLI validator only supports 2.0/3.0.
# The contract comes directly from utoipa; API tests check the request example.
"$generator" "$staging/openapi.json" \
    --output "$staging/http" \
    --output-type OneRequestPerFile \
    --skip-validation \
    --no-logging
cargo run --quiet -p wien-server --locked \
    --example apply-http-examples -- "$staging/openapi.json" "$staging/http"

marker='# Generated by just generate. Do not edit; copy to a separate .http file for experiments.'
shopt -s nullglob
generated=("$staging"/http/*.http)
if [[ ${#generated[@]} -eq 0 ]]; then
    echo "httpgenerator produced no .http files" >&2
    exit 1
fi

# Check every destination before changing any files. Handwritten requests are preserved.
for file in "${generated[@]}"; do
    destination="server/http/$(basename "$file")"
    if [[ -e "$destination" || -L "$destination" ]]; then
        if [[ -L "$destination" || "$(head -n 1 "$destination")" != "$marker" ]]; then
            echo "Refusing to overwrite handwritten file: $destination" >&2
            exit 1
        fi
    fi
    { printf '%s\n\n' "$marker"; cat "$file"; } > "$file.marked"
    mv "$file.marked" "$file"
done

if [[ "$mode" == --check ]]; then
    cmp server/openapi.json "$staging/openapi.json"
    for file in "${generated[@]}"; do
        cmp "server/http/$(basename "$file")" "$file"
    done
else
    mkdir -p server/http
    mv "$staging/openapi.json" server/openapi.json
    for file in "${generated[@]}"; do
        cp "$file" "server/http/$(basename "$file")"
    done
fi

# Remove only stale files owned by this command, never unrelated requests.
for file in server/http/*.http; do
    if [[ "$(head -n 1 "$file")" == "$marker" && ! -f "$staging/http/$(basename "$file")" ]]; then
        if [[ "$mode" == --check ]]; then
            echo "Stale generated request: $file. Run just generate." >&2
            exit 1
        fi
        rm "$file"
    fi
done
echo "HTTP requests: ${#generated[@]} ($mode)"
